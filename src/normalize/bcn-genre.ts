/**
 * Último recurso: deducir del título cuando no está en la tabla.
 * Las formas van acentuadas y sin acentuar ("electrónica" / "electronic"), que
 * es como las escribe la fuente.
 */
const TITLE_HINTS: ReadonlyArray<[RegExp, AppGenre]> = [
  [/\bjazz\b|\bblues\b|\bsoul\b|\bfunk\b/i, 'jazz'],
  [/\brock\b/i, 'rock'],
  [/\bpop\b/i, 'pop'],
  // `elec[a-z]*nic[a-z]*` a propósito: `\w` no cubre la `ó` de
  // "electrónica" y el patrón nunca casaba con la forma acentuada.
  [/elec[a-záéíóúàèòâêîôûäëïöüñ]*nic[a-záéíóúàèòâêîôûäëïöüñ]*|tecno|edm|techno/i, 'electronic'],
  [/flamen[co]|folk|world|salsa|tango/i, 'pop'],
];

/**
 * Género de la agenda municipal para un título, o `null` si no se sabe.
 * Se llama DESPUÉS de `mapGenre`: si el propio título ya delata el género
 * (y así lo hace la fuente), manda esa señal.
 */
export function genreFromTitle(title: string): AppGenre | null {
  const key = normalizeText(title);
  const fromTable = BCN_TITLE_GENRE[key];
  // `undefined` = título no está en la tabla; `null` = clasificada como
  // clásica y la app no tiene ese género. En ambos casos se intenta la pista
  // del propio título antes de rendirse.
  if (fromTable) return fromTable;
  for (const [pattern, genre] of TITLE_HINTS) {
    if (pattern.test(title)) return genre;
  }
  return null;
}
